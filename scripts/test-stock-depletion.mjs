import assert from 'node:assert/strict';
import { freshStock, readStock, mergeInventory } from '../supabase/functions/_shared/inventory.ts';
import { depletionDays } from '../src/lib/stockDepletion.ts';
const now = Date.parse('2026-11-23T04:42:00Z');
assert.equal(freshStock({ stockOnHand: 20, stockUpdatedAt: '2026-11-23T04:00:00Z' }, now), 20);
assert.equal(freshStock({ stockOnHand: 20, stockUpdatedAt: '2026-08-19T04:00:00Z' }, now), null);
assert.equal(freshStock({ stockOnHand: 0 }, now), null);
assert.equal(freshStock(undefined, now), null);
assert.equal(freshStock({ stockOnHand: 0, stockUpdatedAt: '2026-11-23T04:00:00Z' }, now), 0);
assert.equal(readStock({ stock_on_hand: '' }), null);
assert.equal(readStock({ stock_on_hand: 'no' }), null);
assert.equal(readStock({ stock_on_hand: '0' }), 0);
assert.equal(depletionDays(null, 2), null);
assert.equal(depletionDays(20, 2), 10);
assert.equal(depletionDays(-5, 2), 0);
assert.equal(depletionDays(20, 0), null);
const old = { A: { stockOnHand: 2, vendorName: 'Vendor', unitCost: 115.95, onPurchaseOrder: 9 }, B: { stockOnHand: 4, stockUpdatedAt: '2026-11-23T04:41:00Z' } };
const merged = mergeInventory(old, { A: { stockOnHand: 10, itemName: 'Item' }, B: { stockOnHand: 1, itemName: 'Other' } }, '2026-11-23T04:40:00Z');
assert.equal(merged.A.unitCost, 115.95);
assert.equal(merged.A.onPurchaseOrder, 9);
assert.equal(merged.A.stockOnHand, 10);
assert.equal(merged.B.stockOnHand, 4);
assert.equal(mergeInventory(old, {}, '2026-11-23T04:40:00Z').A.stockOnHand, null);
assert.equal(old.A.stockOnHand, 2);
console.log('Stock freshness, depletion and inventory merge tests passed');