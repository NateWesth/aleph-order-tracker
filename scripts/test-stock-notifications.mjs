const now=(await db.query('SELECT now() AS ts')).rows[0].ts.toISOString();
const stale = new Date(Date.parse(now)-48*3600000).toISOString();
const makePayload = quantity => ({A:{stockOnHand:quantity,stockUpdatedAt:now},STALE:{stockOnHand:0,stockUpdatedAt:stale},'M-MISC':{stockOnHand:0,stockUpdatedAt:now}});
