const require = createRequire(new URL('../tests/workflow-safety/package.json', import.meta.url));
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
 CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 CREATE TABLE profiles(id uuid PRIMARY KEY,approved boolean);
 CREATE FUNCTION is_user_approved(user_uuid uuid) RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=public AS $$ SELECT coalesce((SELECT approved FROM profiles WHERE id=user_uuid),false) $$;
 CREATE TABLE order_items(code text,quantity integer,created_at timestamptz,completed_at timestamptz,progress_stage text);
 CREATE TABLE buying_sheet_cache(id text PRIMARY KEY,payload jsonb,fetched_at timestamptz);
 CREATE TABLE notifications(id uuid DEFAULT gen_random_uuid(),user_id uuid,type text,title text,message text,metadata jsonb);
 CREATE TABLE push_events(notification_id uuid);
 CREATE FUNCTION dispatch_comment_push() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$ BEGIN IF NEW.type IN ('entity_comment','comment_reply') THEN INSERT INTO push_events VALUES(NEW.id); END IF; RETURN NEW; END; $$;
 CREATE TRIGGER test_push AFTER INSERT ON notifications FOR EACH ROW EXECUTE FUNCTION dispatch_comment_push();
 GRANT USAGE ON SCHEMA public,auth TO authenticated;
`);
const directory = new URL('../supabase/migrations/', import.meta.url);
